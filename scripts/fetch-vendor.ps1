<#
.SYNOPSIS
  Downloads the frontend third-party assets used by Trend Detective.

.DESCRIPTION
  - Leaflet 1.9.4 (JS, CSS, marker images)
  - Chart.js 4 (UMD build)
  - Lucide icons used by the design, compiled into a single SVG sprite
    (frontend/assets/icons/sprite.svg). Each icon becomes a <symbol id="name">.

  Run from the repository root:  powershell -File scripts/fetch-vendor.ps1
#>
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$root = Split-Path -Parent $PSScriptRoot
$vendor = Join-Path $root 'frontend/assets/vendor'
$iconsDir = Join-Path $root 'frontend/assets/icons'
New-Item -ItemType Directory -Force -Path "$vendor/leaflet/images", "$vendor/chartjs", $iconsDir | Out-Null

function Get-File($url, $target) {
  Write-Host "GET $url"
  Invoke-WebRequest -Uri $url -OutFile $target -UseBasicParsing
}

# --- Leaflet ---------------------------------------------------------------
$leaflet = 'https://unpkg.com/leaflet@1.9.4/dist'
Get-File "$leaflet/leaflet.js" "$vendor/leaflet/leaflet.js"
Get-File "$leaflet/leaflet.css" "$vendor/leaflet/leaflet.css"
foreach ($img in 'marker-icon.png', 'marker-icon-2x.png', 'marker-shadow.png', 'layers.png', 'layers-2x.png') {
  Get-File "$leaflet/images/$img" "$vendor/leaflet/images/$img"
}

# --- Chart.js --------------------------------------------------------------
Get-File 'https://unpkg.com/chart.js@4/dist/chart.umd.min.js' "$vendor/chartjs/chart.umd.min.js"

# --- Lucide icons -> SVG sprite -------------------------------------------
# Keys are the sprite ids used in the HTML; values are candidate lucide-static
# file names (newer names first, legacy aliases as fallback).
$icons = [ordered]@{
  'arrow-right'     = @('arrow-right')
  'arrow-up-right'  = @('arrow-up-right')
  'chart-column'    = @('chart-column', 'bar-chart-3')
  'book-open'       = @('book-open')
  'check'           = @('check')
  'circle-check'    = @('circle-check', 'check-circle-2')
  'code-xml'        = @('code-xml', 'code-2')
  'crosshair'       = @('crosshair')
  'database'        = @('database')
  'download'        = @('download')
  'earth'           = @('earth', 'globe-2')
  'external-link'   = @('external-link')
  'filter'          = @('funnel', 'filter')
  'flask-conical'   = @('flask-conical')
  'heart-handshake' = @('heart-handshake')
  'loader-circle'   = @('loader-circle', 'loader-2')
  'map-pin'         = @('map-pin')
  'menu'            = @('menu')
  'microscope'      = @('microscope')
  'moon'            = @('moon')
  'orbit'           = @('orbit')
  'play'            = @('play')
  'rotate-ccw'      = @('rotate-ccw')
  'satellite'       = @('satellite')
  'scale'           = @('scale')
  'search'          = @('search')
  'shield-alert'    = @('shield-alert')
  'shield-check'    = @('shield-check')
  'sigma'           = @('sigma')
  'sparkles'        = @('sparkles')
  'sun'             = @('sun')
  'trending-up'     = @('trending-up')
  'triangle-alert'  = @('triangle-alert', 'alert-triangle')
  'x'               = @('x')
}

$symbols = foreach ($id in $icons.Keys) {
  $svg = $null
  foreach ($candidate in $icons[$id]) {
    try {
      $svg = (Invoke-WebRequest -Uri "https://unpkg.com/lucide-static@latest/icons/$candidate.svg" -UseBasicParsing).Content
      break
    } catch { Write-Host "  missing $candidate, trying next" }
  }
  if (-not $svg) { throw "Icon '$id' could not be downloaded." }
  if ($svg -is [byte[]]) { $svg = [Text.Encoding]::UTF8.GetString($svg) }
  # Keep only the drawing primitives inside the root <svg> element.
  $inner = [regex]::Match($svg, '(?s)<svg[^>]*>(.*)</svg>').Groups[1].Value
  $inner = [regex]::Replace($inner, '(?s)<!--.*?-->', '')
  $inner = ($inner -split "`n" | ForEach-Object { $_.Trim() } | Where-Object { $_ }) -join ''
  "  <symbol id=`"$id`" viewBox=`"0 0 24 24`">$inner</symbol>"
}

$sprite = @"
<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
<!-- Lucide icons (ISC License, https://lucide.dev). Generated by scripts/fetch-vendor.ps1 -->
$($symbols -join "`n")
</svg>
"@
[IO.File]::WriteAllText((Join-Path $iconsDir 'sprite.svg'), $sprite, (New-Object Text.UTF8Encoding $false))
Write-Host "Sprite written with $($icons.Count) icons."
